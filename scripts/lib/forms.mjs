const q = (s) => JSON.stringify(String(s)); // JSON strings are valid YAML double-quoted scalars

export function renderNewEntryForm() {
  const L = [
    '# GENERATED by scripts/sync.mjs from scripts/lib/forms.mjs and schema/categories.json. Do not edit by hand.',
    'name: New entry',
    'description: Submit a new resource for the Index Agentica directory (agents welcome).',
    'title: "[New entry]: "',
    'labels: ["submission", "new-entry"]',
    'body:',
    '  - type: markdown',
    '    attributes:',
    '      value: ' + q('Fields map 1:1 to the [entry schema](https://indexagentica.com/schema/). A maintainer reviews the submission; adding the `approved` label opens a pull request automatically. Prefer a direct PR? See https://indexagentica.com/agents/#contribute'),
  ];
  for (const f of formFields()) {
    L.push(`  - type: ${f.type}`, `    id: ${f.key.replace(/\./g, '_')}`, '    attributes:', `      label: ${q(f.label)}`);
    if (f.description) L.push(`      description: ${q(f.description)}`);
    if (f.placeholder) L.push(`      placeholder: ${q(f.placeholder)}`);
    if (f.options) { L.push('      options:'); f.options.forEach((o) => L.push(`        - ${q(o)}`)); }
    L.push('    validations:', `      required: ${!!f.required}`);
  }
  L.push(
    '  - type: checkboxes',
    '    id: confirm',
    '    attributes:',
    '      label: Confirmation',
    '      options:',
    `        - label: ${q('The facts above are verifiable from the listed sources, and any affiliation with the resource is disclosed in the description or notes.')}`,
    '          required: true',
  );
  return L.join('\n') + '\n';
}

// Markdown body equivalent to what the form produces: for agents that create issues via the API.
export function issueBodyTemplate() {
  return formFields().map((f) => `### ${f.label}\n\n${f.required ? `<${f.key}>` : '_No response_'}`).join('\n\n') + '\n';
}

// Parse an issue-form body into { entry, problems }. Does not validate against the schema.
export function parseIssueBody(body) {
  // Only headings that match a known form label start a section, so "###" inside a
  // markdown description doesn't break parsing.
  const known = new Set([...formFields().map((f) => f.label.toLowerCase()), 'confirmation']);
  const sections = {};
  let current = null;
  for (const line of String(body || '').replace(/\r\n?/g, '\n').split('\n')) {
    const m = line.match(/^###[ \t]+(.+?)\s*$/);
    if (m && known.has(m[1].toLowerCase())) { current = m[1].toLowerCase(); sections[current] = []; continue; }
    if (current) sections[current].push(line);
  }
  for (const k of Object.keys(sections)) {
    let value = sections[k].join('\n').trim();
    if (value === '_No response_' || value === 'None') value = '';
    sections[k] = value;
  }
  const entry = {};
  const problems = [];
  for (const f of formFields()) {
    let v = sections[f.label.toLowerCase()];
    if (v === undefined) { if (f.required) problems.push(`Missing section "### ${f.label}"`); continue; }
    if (f.type === 'input') v = v.replace(/^`+|`+$/g, '').trim();
    if (!v) { if (f.required) problems.push(`"${f.label}" is required`); continue; }
    if (f.list === 'comma') v = v.split(/[,\n]/).map((s) => s.trim()).filter(Boolean);
    if (f.list === 'lines') v = v.split('\n').map((s) => s.replace(/^\s*(?:[-*+]|\d+\.)\s+/, '').replace(/^<|>$/g, '').trim()).filter(Boolean);
    if (f.key === 'tags') v = v.map((t) => t.toLowerCase().replace(/\s+/g, '-'));
    const [a, b] = f.key.split('.');
    if (b) (entry[a] ||= {})[b] = v;
    else entry[a] = v;
  }
  return { entry, problems };
}

// Single definition of the "New entry" submission form. Used to:
//  - generate .github/ISSUE_TEMPLATE/new-entry.yml (scripts/sync.mjs)
//  - parse submitted issue bodies into entry JSON (scripts/issue-to-entry.mjs)
//  - publish a plain-markdown issue body template for API-only agents (/contribute.json)
// GitHub renders issue-form answers as "### <label>\n\n<value>", so labels are the parse keys:
// never rename a label without regenerating the form (node scripts/sync.mjs).
import { loadCategories } from './categories.mjs';

